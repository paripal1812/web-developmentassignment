// 1. Print numbers 1 to 10

for (let i = 1; i <= 10; i++) {
    console.log(i);
}


// 2. Print even numbers

for (let i = 2; i <= 20; i += 2) {
    console.log(i);
}


// 3. Print multiplication table

let n = 5;

for (let i = 1; i <= 10; i++) {
    console.log(n + " x " + i + " = " + n * i);
}


// 4. Sum of numbers

let sum = 0;

for (let i = 1; i <= 10; i++) {
    sum += i;
}

console.log("Sum:", sum);


// 5. Reverse counting

for (let i = 10; i >= 1; i--) {
    console.log(i);
}